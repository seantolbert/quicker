import type { Manifest } from "./manifest";

export function agentsMd(manifest: Manifest) {
  const rows = manifest.sections
    .map(
      (s) =>
        `| \`${s.id}\` | ${s.label} | \`${s.variant}\` | \`${s.component}\` | ${s.components.map((c) => `\`${c}\``).join(" ")} | ${[...s.motion.effects, ...(s.motion.concept ? ["concept"] : [])].join(", ") || "none"} |`,
    )
    .join("\n");

  return `# ${manifest.name}: agent guide

This site was generated by Quicker. Every section and component is labeled so
you can find and change things by ID instead of guessing. Keep the labels
intact when you edit.

## Where things live

| What | Where |
| --- | --- |
| All copy and section content | \`src/content/site.ts\` keyed by section ID |
| Section order | \`src/app/page.tsx\` (each section has an \`@section\` comment) |
| Section layout and markup | \`src/components/sections/<type>/<Component>.tsx\` |
| Section prop types | \`src/components/sections/<type>/schema.ts\` |
| Colors, fonts, radius | \`src/app/globals.css\` (\`--q-*\` variables) and \`src/app/layout.tsx\` (fonts) |
| Machine-readable map | \`site.manifest.json\` |

## Labeling contract

- Section root: \`data-section="<type>"\`, \`data-section-id="<type>-<n>"\`, \`data-variant\`, and \`id\` equal to the section ID.
- Elements inside: \`data-component="<type>.<name>"\`. Repeated items add \`data-index\` (0-based).
- Selectors: \`[data-section-id="hero-1"] [data-component="hero.headline"]\`, \`[data-section-id="pricing-1"] [data-component="pricing.tier"][data-index="1"]\`.
- Photo placeholders carry \`data-placeholder="image"\`; their alt text says what photo belongs there.
- Real photos carry \`data-rights\`: \`sample_only\` (from the Google listing, demo only), \`pending_client_confirmation\` (from the business's website), or \`client_confirmed\`. Only \`client_confirmed\` images may go on a live site. Files are in \`public/photos/\` and \`public/brand/\`.
- Placeholder stats or reviews show a visible "Placeholder" badge (\`<type>.placeholder\`) and \`placeholder: true\` in content.

When you add a section: give it the next free \`<type>-<n>\` ID, spread \`sectionAttrs(...)\` on its root and
\`cmp("<type>.<name>")\` on its parts (from \`src/components/sections/labels.ts\`), add its content to
\`src/content/site.ts\`, and add an entry to \`site.manifest.json\`.

## Motion

- One provider: \`MotionRoot\` (\`src/components/sections/_motion/MotionRoot.tsx\`) wraps the page in \`src/app/layout.tsx\`. It runs Lenis smooth scroll
  and GSAP ScrollTrigger (registered once), **only at 768px and wider with no reduced-motion preference**. Everywhere else the page is static and fully visible.
- Signature concept: **\`${manifest.motion.concept}\`**. ${manifest.motion.description} Source: \`${manifest.motion.direction}\`.
  Concept markup carries \`data-concept="${manifest.motion.concept}"\`; its animation lives in \`_motion/runtime.ts\` (\`applyConcept\`).
- Shared quiet layer: elements opt in with \`data-motion\` (use the \`motion("…")\` helper from \`_motion/vocabulary.ts\`):
${Object.entries(manifest.motion.effects)
  .map(([k, v]) => `  - \`${k}\`: ${v}`)
  .join("\n")}
- To turn an effect off, remove its \`data-motion\` attribute. To change the concept, change it in the direction file and in \`layout.tsx\` / \`page.tsx\`.
- Rules: no UI animation over 800 ms; hero text never animates; nothing loops. lenis and gsap are pinned; don't upgrade without asking.

## Sections on this page

| ID | Section | Variant | Component | Labels | Motion |
| --- | --- | --- | --- | --- | --- |
${rows}

## Common edits

- Change copy: edit the matching key in \`src/content/site.ts\`. Types catch missing fields.
- Reorder: move the JSX lines in \`src/app/page.tsx\`. Update anchor links (\`#<section-id>\`) if needed.
- Restyle one section type: edit its component. Use the \`site-*\` Tailwind tokens (\`bg-site-bg\`, \`text-site-muted\`, \`bg-site-primary\`, \`rounded-site\`, \`font-heading\`) rather than raw colors.
- Swap a photo placeholder: replace the \`<Media>\` element with \`next/image\` and keep its \`data-component\`.
`;
}
